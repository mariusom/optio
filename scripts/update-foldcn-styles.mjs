#!/usr/bin/env node
/**
 * Regenerates the runtime class table from foldcn's resolved registries.
 * Source: https://github.com/elianiva/foldcn (MIT), served from the URLs below.
 */
import { readFile, writeFile } from "node:fs/promises";

const styles = ["nova", "vega", "maia", "lyra", "mira", "luma", "sera", "rhea"];
const components = [
  "alert-dialog",
  "badge",
  "button",
  "card",
  "checkbox",
  "dialog",
  "empty",
  "input",
  "item",
  "label",
  "native-select",
  "progress",
  "radio-group",
  "separator",
  "sheet",
  "skeleton",
  "switch",
  "textarea",
];

const strings = (source) => {
  // Registry variants are generated from one source tree and differ only in
  // resolved string contents, so their string-literal positions are stable.
  const found = [];
  for (let index = 0; index < source.length; index++) {
    const quote = source[index];
    if (quote !== "'" && quote !== '"' && quote !== "`") continue;
    let value = "";
    for (index++; index < source.length; index++) {
      const character = source[index];
      if (character === "\\") {
        value += character + (source[++index] ?? "");
      } else if (character === quote) break;
      else value += character;
    }
    found.push(value.replaceAll("\\'", "'").replaceAll('\\"', '"'));
  }
  return found;
};

const namedStrings = (source) => {
  const found = new Map();
  const declaration =
    /(?:export\s+)?const\s+([A-Za-z_$][\w$]*)[^=]*=([\s\S]*?)(?=\n(?:export\s+)?(?:const|type|function)\s|$)/g;
  for (const match of source.matchAll(declaration))
    strings(match[2]).forEach((value, index) => found.set(`${match[1]}.${index}`, value));
  return found;
};

const load = async (style, component) => {
  const url = `https://foldcn.elianiva.com/r/styles/${style}/${component}.json`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} fetching ${url}`);
  const json = await response.json();
  return namedStrings(json.files[0].content);
};

const table = Object.fromEntries(styles.map((style) => [style, {}]));
for (const component of components) {
  const sources = Object.fromEntries(
    await Promise.all(styles.map(async (style) => [style, await load(style, component)])),
  );
  const local = namedStrings(await readFile(`src/components/ui/${component}.ts`, "utf8"));
  const candidates = [...sources.nova.entries()].filter(([, value]) => value.includes(" "));
  for (const [localPath, value] of [...local.entries()].filter(([, item]) => item.includes(" "))) {
    const localTokens = new Set(value.split(/\s+/));
    const exact = sources.nova.get(localPath);
    const nova =
      exact !== undefined
        ? { path: localPath, candidate: exact, score: 1 }
        : candidates
            .map(([path, candidate]) => {
              const tokens = new Set(candidate.split(/\s+/));
              const overlap = [...localTokens].filter((token) => tokens.has(token)).length;
              return { path, candidate, score: overlap / Math.max(localTokens.size, tokens.size) };
            })
            .sort((a, b) => b.score - a.score)[0];
    if (nova === undefined || nova.score < 0.55) continue;
    for (const style of styles) {
      const resolved = sources[style].get(nova.path);
      if (resolved === undefined || resolved === nova.candidate) continue;
      const novaTokens = new Set(nova.candidate.split(/\s+/));
      const customTokens = [...localTokens].filter((token) => !novaTokens.has(token));
      table[style][value] = `${resolved} ${customTokens.join(" ")}`.trim();
    }
  }
}

const output =
  `// Generated by scripts/update-foldcn-styles.mjs; do not edit.\n` +
  `// foldcn resolved registries, retrieved ${new Date().toISOString().slice(0, 10)}.\n` +
  `export const foldcnComponentStyles: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(table, null, 2)};\n`;
await writeFile("src/we/componentStyles.generated.ts", output);
